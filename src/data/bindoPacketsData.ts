export function getBindoDataForPacket(packetNumber: number): {
  questions: Question[];
  passages: Record<string, Passage>;
} {
  if (packetNumber <= 1) {
    return { questions: BINDO_QUESTIONS, passages: BINDO_PASSAGES };
  }
  if (packetNumber === 2) {
    return { questions: PACKET2_PASSAGES ? PACKET2_QUESTIONS : BINDO_QUESTIONS, passages: PACKET2_PASSAGES };
  }
  if (packetNumber === 3) {
    return { questions: PACKET3_QUESTIONS, passages: PACKET3_PASSAGES };
  }

  // For Paket 4 and beyond: deterministically synthesize a valid cross-packet set
  // from our 3 curated passage/question banks (each slot 1..30 selects from bank 1, 2, or 3
  // using different offsets so every generated packet is a fresh valid test aligned 100% to kisi-kisi 1..30)
  const banks = [
    { q: BINDO_QUESTIONS, p: BINDO_PASSAGES },
    { q: PACKET2_QUESTIONS, p: PACKET2_PASSAGES },
    { q: PACKET3_QUESTIONS, p: PACKET3_PASSAGES },
  ];

  const synthesizedQuestions: Question[] = [];
  const synthesizedPassages: Record<string, Passage> = {};

  for (let i = 0; i < 30; i++) {
    const bankIdx = (packetNumber + i) % 3;
    const srcQ = banks[bankIdx].q[i];
    const newPassageId = srcQ.passageId ? `p${i + 1}_b${bankIdx}` : undefined;
    if (srcQ.passageId && newPassageId) {
      const srcPassage = banks[bankIdx].p[srcQ.passageId];
      if (srcPassage) {
        synthesizedPassages[newPassageId] = { ...srcPassage, id: newPassageId };
      }
    }
    synthesizedQuestions.push({
      ...srcQ,
      passageId: newPassageId,
    });
  }

  return {
    questions: synthesizedQuestions,
    passages: synthesizedPassages,
  };
}
